/**
 * Curated 100-song fallback catalog per genre (1,000 tracks total across 10 genres).
 * Used when live Deezer / iTunes / Spotify APIs time out or return insufficient tracks.
 */

function makeGenreTracks(subCategory, prefix, items) {
  return items.map(([title, artist, album], idx) => ({
    spotifyId: `fb_${prefix}_${idx + 1}`,
    title,
    artist,
    primaryArtist: artist.split(',')[0].trim(),
    album: album || title,
    category: 'Genre',
    subCategory
  }));
}

